"""Make the data for the three live demos in lec15.qmd: pics/lec15/demos-data.js.

The demos themselves are in pics/lec15/demos.js (hand-written). This script only packs their data, as
data: URIs and numbers inside a .js file, so the deck also works when opened straight from disk (a
fetched file or a canvas read from a file:// image would be blocked there).

Needs an env with numpy, Pillow, scikit-image and torchvision (`genaibook` has all four). Run from the
slides folder:

    python pics/lec15_demos.py [CIFAR_ROOT]          # default CIFAR_ROOT: ~/data

  noise   scikit-image's `chelsea` (CC0), 192 x 192, as in pics/lec15_16_figs.py
  cats    the first 1,000 cats in the CIFAR-10 training set (Krizhevsky, 2009), 32 x 32, as one PNG
          sprite 40 images wide
  spiral  500 points on a two-armed spiral, scaled so each coordinate has standard deviation 1
"""
import base64
import io
import json
import sys
from pathlib import Path

import numpy as np
from PIL import Image

HERE = Path(__file__).resolve().parent
OUT = HERE / 'lec15' / 'demos-data.js'
N_CATS, COLS = 1000, 40


def data_uri(im, fmt='PNG', **kw):
    buf = io.BytesIO()
    im.save(buf, fmt, **kw)
    return f'data:image/{fmt.lower()};base64,' + base64.b64encode(buf.getvalue()).decode()


def check_schedule():
    """The JS rebuilds alpha-bar from linspace(1e-4, 0.02, 1000); make sure that matches the deck."""
    ab = np.cumprod(1 - np.linspace(1e-4, 0.02, 1000))
    ref = np.loadtxt(HERE / 'lec15' / 'alphabar-ddpm.txt')     # every 10th value, 5 decimals
    assert np.allclose(ab[::10], ref, atol=1e-5), 'schedule mismatch'


def chelsea(res=192):
    import importlib.util                                    # read the file: skimage.data pulls in scipy
    im = Image.open(Path(importlib.util.find_spec('skimage').origin).parent / 'data' / 'chelsea.png').convert('RGB')
    # 300 x 451, same crop as lec15_16_figs.py
    w, h = im.size
    return im.crop(((w - h) // 2 + 30, 0, (w - h) // 2 + 30 + h, h)).resize((res, res), Image.LANCZOS)


def cats(root):
    from torchvision.datasets import CIFAR10
    ds = CIFAR10(root=root, train=True, download=False)
    cat = ds.classes.index('cat')
    idx = [i for i, y in enumerate(ds.targets) if y == cat][:N_CATS]
    sprite = Image.new('RGB', (COLS * 32, (N_CATS // COLS) * 32))
    for k, i in enumerate(idx):
        r, c = divmod(k, COLS)
        sprite.paste(Image.fromarray(ds.data[i]), (c * 32, r * 32))
    return sprite


def spiral(n=500, seed=0):
    rng = np.random.default_rng(seed)
    th = np.sqrt(rng.uniform(0.15, 1, n)) * 3.2 * np.pi    # even spacing along the arm
    arm = rng.integers(0, 2, n) * np.pi                       # two arms, opposite each other
    p = np.stack([th * np.cos(th + arm), th * np.sin(th + arm)], 1)
    p += rng.normal(0, 0.25, p.shape)
    p = (p - p.mean(0)) / p.std(0)
    return [round(float(v), 3) for v in p.ravel()]


def main():
    root = Path(sys.argv[1] if len(sys.argv) > 1 else '~/data').expanduser()
    check_schedule()
    d = {'chelsea': data_uri(chelsea()),
         'cats': {'n': N_CATS, 'cols': COLS, 'src': data_uri(cats(root))},
         'spiral': spiral()}
    OUT.write_text('// Generated by pics/lec15_demos.py; do not edit.\nwindow.L15DATA = '
                   + json.dumps(d, separators=(',', ':')) + ';\n')
    print('wrote', OUT, f'{OUT.stat().st_size / 1e6:.2f} MB')


if __name__ == '__main__':
    main()
