def blurred(v):
    """A soft copy of the digit, standing in for a lossy reconstruction."""
    n = len(v)
    out = [[0.0] * n for _ in range(n)]
    for r in range(n):
        for c in range(n):
            s = w = 0.0
            for dr in (-1, 0, 1):
                for dc in (-1, 0, 1):
                    if 0 <= r + dr < n and 0 <= c + dc < n:
                        k = 2.0 if dr == dc == 0 else 1.0
                        s += k * v[r + dr][c + dc]
                        w += k
            out[r][c] = min(1.0, 1.25 * s / w)
    return out


