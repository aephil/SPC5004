def lec11_shapes():
    p = 'l11d'
    cy, k = 222, 5.6
    sizes = []
    for kind, ch, hw, _ in LAYERS:
        if kind == 'z':
            sizes.append((14, 0))
        else:
            sizes.append((hw * k, 2 + ch * 0.28))
    total = sum(s + d for s, d in sizes)
    gap = (1060 - total) / (len(sizes) - 1)
    b, x, xs = [], 20.0, []
    for (kind, ch, hw, lab), (s, d) in zip(LAYERS, sizes):
        xs.append(x)
        if kind == 'z':
            b.append(zvec(x, cy - 48, 16, 14, 6, 3))
            b.append(text(x + 7, cy - 58, 'z', 18, w=600, i=True))
            cxl = x + 7
        else:
            fill = {'img': '#ffffff', 'out': '#ffffff', 'enc': ENC, 'dec': DEC}[kind]
            face = None
            if kind in ('img', 'out'):
                face = pixels(x, cy - s / 2, X if kind == 'img' else XHAT, k, stroke='#222')
            b += cube(x, cy, s, d, fill, face)
            cxl = x + s / 2
        b.append(text(cxl, cy + 28 * k / 2 + 30, lab, 13, mono=True, c=ACC if kind == 'z' else '#000'))
        x += s + d + gap
    for i in range(len(sizes) - 1):
        s, d = sizes[i]
        b.append(arrow(p, xs[i] + s + d + 3, xs[i + 1] - 4, cy))
    e_end = xs[4] + sum(sizes[4])
    b += bracket(20, e_end, 96, 'Encoder: four strided convolutions, then a linear layer', '#2f7d4a')
    b += bracket(xs[6], 1080, 96, 'Decoder: a linear layer, three transposed convolutions, a sigmoid', '#a23aa6')
    b.append(text(540, 360, 'shapes are channels × height × width; summary() also puts the batch size in front', 13, c=GREY))
    return svg(p, 1100, 372, "Tensor shapes through the lab's autoencoder", b, markers(p, {'k': '#222'}))


