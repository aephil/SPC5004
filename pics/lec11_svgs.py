# ---------- helpers ----------
def pixels(x, y, vals, cs, stroke='#555'):
    """A greyscale image as in plt.imshow(..., cmap='gray_r'): white background, dark ink."""
    n = len(vals)
    out = [f'<rect x="{f(x)}" y="{f(y)}" width="{f(n * cs)}" height="{f(n * cs)}" fill="#fff"/>']
    for r, row in enumerate(vals):
        for c, v in enumerate(row):
            if v > 0.02:
                out.append(f'<rect x="{f(x + c * cs)}" y="{f(y + r * cs)}" width="{f(cs + 0.15)}" '
                           f'height="{f(cs + 0.15)}" fill="{mix("#ffffff", PIX, v)}"/>')
    out.append(f'<rect x="{f(x)}" y="{f(y)}" width="{f(n * cs)}" height="{f(n * cs)}" fill="none" '
               f'stroke="{stroke}" stroke-width="1"/>')
    return '\n'.join(out)


def photo(x, y, n, cs):
    """A blocky stand-in for a colour photograph: sky, sun, hills."""
    out = []
    for r in range(n):
        for c in range(n):
            t = r / (n - 1)
            hill = 0.55 + 0.08 * ((c - n * 0.3) / n) ** 2 * 8
            if (r - n * 0.25) ** 2 + (c - n * 0.72) ** 2 < (n * 0.11) ** 2:
                col = '#f2a65a'
            elif t < hill:
                col = mix('#d6e8f7', '#86b6df', t / hill)
            else:
                col = mix('#a5c97f', '#5b8a46', (t - hill) / (1 - hill))
            out.append(f'<rect x="{f(x + c * cs)}" y="{f(y + r * cs)}" width="{f(cs + 0.15)}" '
                       f'height="{f(cs + 0.15)}" fill="{col}"/>')
    out.append(f'<rect x="{f(x)}" y="{f(y)}" width="{f(n * cs)}" height="{f(n * cs)}" fill="none" '
               f'stroke="#555" stroke-width="1"/>')
    return '\n'.join(out)


def trap(x1, x2, h1, h2, cy, fill, label=None, sub=None, fs=20):
    """An encoder (h1 > h2) or decoder (h1 < h2) drawn as a tapering block, as in lec01."""
    pts = [(x1, cy - h1 / 2), (x2, cy - h2 / 2), (x2, cy + h2 / 2), (x1, cy + h1 / 2)]
    d = 'M' + ' L'.join(f'{f(a)} {f(b)}' for a, b in pts) + ' Z'
    out = [f'<path d="{d}" fill="{fill}" stroke="#222" stroke-width="2.4" stroke-linejoin="round"/>']
    if label:
        out.append(text((x1 + x2) / 2, cy + (-2 if sub else 6), label, fs, w=700))
    if sub:
        out.append(text((x1 + x2) / 2, cy + 18, sub, 13, c=DARK))
    return out


def zvec(x, y, n, cw, ch, seed):
    """The latent vector z: a column of n tinted cells."""
    return grid(x, y, n, 1, cw, ch, ACC, seed, stroke='#222')


def cube(x, cy, side, d, fill, face=None):
    """A C×H×W feature map: the front face is H×W, the depth stands for the channels."""
    dx, dy = d, -0.6 * d
    top = cy - side / 2
    out = [f'<path d="M{f(x + side)} {f(top)} L{f(x + side + dx)} {f(top + dy)} V{f(top + side + dy)} '
           f'L{f(x + side)} {f(top + side)} Z" fill="{mix(fill, "#000000", 0.12)}" stroke="#222" '
           f'stroke-width="1.2" stroke-linejoin="round"/>',
           f'<path d="M{f(x)} {f(top)} L{f(x + dx)} {f(top + dy)} H{f(x + side + dx)} L{f(x + side)} {f(top)} Z" '
           f'fill="{mix(fill, "#ffffff", 0.35)}" stroke="#222" stroke-width="1.2" stroke-linejoin="round"/>']
    if face:
        out.append(face)
        out.append(f'<rect x="{f(x)}" y="{f(top)}" width="{f(side)}" height="{f(side)}" fill="none" '
                   f'stroke="#222" stroke-width="1.2"/>')
    else:
        out.append(f'<rect x="{f(x)}" y="{f(top)}" width="{f(side)}" height="{f(side)}" fill="{fill}" '
                   f'stroke="#222" stroke-width="1.2"/>')
    return out


def stack(x, y, side, k, off, fills, face=None):
    """k channels as offset squares, the front one optionally showing `face`."""
    out = []
    for i in reversed(range(k)):
        xx, yy = x + i * off, y - i * off
        if i == 0 and face:
            out.append(face)
        else:
            out.append(rect(xx, yy, side, side, fills[i], '#444', 1.2, 0))
    return out


def arrow(p, x1, x2, y, c='#222'):
    return path([(x1, y), (x2, y)], f'{p}-k', c)


