# ---------- lec07: gradient descent with one parameter ----------
def L(w):
    return (w - 1.5) ** 2 + 2.3


def dL(w):
    return 2 * (w - 1.5)


def lr_axes(X, Y, x0, x1, y0, y1, xt, yt, small=False):
    fs = 11 if small else 13
    b = [f'<path d="M{f(X(x0))} {f(Y(y1))} V{f(Y(y0))} H{f(X(x1))}" fill="none" stroke="#222" stroke-width="1.4"/>']
    for v in xt:
        b.append(f'<path d="M{f(X(v))} {f(Y(y0))} v5" stroke="#222" stroke-width="1.2"/>')
        b.append(text(X(v), Y(y0) + 8 + fs, f'{v:g}', fs, c=DARK))
    for v in yt:
        b.append(f'<path d="M{f(X(x0))} {f(Y(v))} h-5" stroke="#222" stroke-width="1.2"/>')
        b.append(text(X(x0) - 9, Y(v) + fs * 0.35, f'{v:g}', fs, a='end', c=DARK))
    return b


def curve(X, Y, x0, x1, dash='7 5', c=BLUE, w=2.2):
    pts = [(x0 + (x1 - x0) * k / 200) for k in range(201)]
    d = 'M' + ' L'.join(f'{X(x):.1f} {Y(L(x)):.1f}' for x in pts)
    return f'<path d="{d}" fill="none" stroke="{c}" stroke-width="{w}" stroke-dasharray="{dash}"/>'


def lec07_gd():
    p = 'l7g'
    x0, x1, y0, y1 = -8, 11, 0, 90
    X = lambda w: 70 + (w - x0) / (x1 - x0) * 600
    Y = lambda l: 330 - (l - y0) / (y1 - y0) * 300
    eta = 0.3
    ws = [-5.0]
    for _ in range(2):
        ws.append(ws[-1] - eta * dL(ws[-1]))
    b = lr_axes(X, Y, x0, x1, y0, y1, [-5, 0, 5, 10], [0, 20, 40, 60, 80])
    b.append(text(X(1.5), 398, 'parameter value w', 14, w=600, c=GREY))
    b.append(text(26, Y(45), 'loss', 14, w=600, c=GREY, extra=f' transform="rotate(-90 26 {f(Y(45))})"'))

    def point(w, name):
        return [f'<circle cx="{f(X(w))}" cy="{f(Y(L(w)))}" r="6" fill="#000"/>',
                text(X(w) - 12, Y(L(w)) - 10, name, 15, a='end', w=700)]

    def tangent(w):
        # short arrow along the tangent, pointing downhill
        g = dL(w)
        sx, sy = 600 / (x1 - x0), 300 / (y1 - y0)
        dx, dy = sx, -g * sy
        n = math.hypot(dx, dy)
        ln = 62
        return path([(X(w), Y(L(w))), (X(w) + dx / n * ln, Y(L(w)) + dy / n * ln)], f'{p}-r', RED, 2.6)

    def step(wa, wb):
        y = Y(0) + 32   # below the tick labels
        return [f'<path d="M{f(X(wa))} {f(Y(L(wa)) + 8)} V{f(y + 4)}" stroke="{GREY}" stroke-width="1" stroke-dasharray="3 3"/>',
                path([(X(wa), y), (X(wb) - 2, y)], f'{p}-r', RED, 2),
                text((X(wa) + X(wb)) / 2, y + 17, f'+{-eta * dL(wa):.2g}', 13, w=600, c=RED)]

    tx = 720
    b += point(ws[0], 'A')
    b.append(text(tx, 50, f'Start at w = {ws[0]:g}: loss {L(ws[0]):.2f}', 16, a='start'))
    b.append(frag(1, [tangent(ws[0]),
                      text(tx, 84, f'Gradient {dL(ws[0]):.3g}: the loss falls', 16, a='start', c=RED),
                      text(tx, 106, 'if we increase w', 16, a='start', c=RED)]))
    b.append(frag(2, step(ws[0], ws[1]) + point(ws[1], 'B') + [tangent(ws[1]),
                      text(tx, 148, f'Step: w ← {ws[0]:g} − {eta:g} × ({dL(ws[0]):.3g})', 16, a='start'),
                      text(tx, 170, f'= {ws[1]:.2g}. Loss {L(ws[1]):.2f}, gradient {dL(ws[1]):.2g}', 16, a='start')]))
    b.append(frag(3, step(ws[1], ws[2]) + point(ws[2], 'C') + [tangent(ws[2]),
                      text(tx, 212, f'Then w = {ws[2]:.2f}: loss {L(ws[2]):.2f},', 16, a='start'),
                      text(tx, 234, f'gradient {dL(ws[2]):.3g}', 16, a='start')]))
    b.append(frag(4, [curve(X, Y, -7.9, 10.9),
                      text(tx, 276, 'The whole curve (never seen', 16, a='start', c=BLUE),
                      text(tx, 298, 'in practice): the gradient', 16, a='start', c=BLUE),
                      text(tx, 320, 'shrinks near the minimum,', 16, a='start', c=BLUE),
                      text(tx, 342, 'so the steps shrink too.', 16, a='start', c=BLUE)]))
    return svg(p, 1100, 406, 'Gradient descent on a loss curve with one parameter', b, markers(p, {'r': RED}))


def lec07_rates():
    p = 'l7h'
    x0, x1, y0, y1 = -11, 14, 0, 135
    panels = [(0.05, 'too low', 'tiny steps: slow progress', 10),
              (0.3, 'about right', 'close to the minimum in a few steps', 4),
              (1.1, 'too high', 'overshoots further each step: diverges', 3)]
    b = []
    for k, (eta, name, cap, n) in enumerate(panels):
        ox = 20 + k * 362
        X = lambda w, ox=ox: ox + 42 + (w - x0) / (x1 - x0) * 300
        Y = lambda l: 300 - (l - y0) / (y1 - y0) * 250
        body = lr_axes(X, Y, x0, x1, y0, y1, [-10, -5, 0, 5, 10], [0, 50, 100], small=True)
        body.append(curve(X, Y, 1.5 - (y1 - 2.3) ** 0.5, 1.5 + (y1 - 2.3) ** 0.5, '6 4', BLUE, 1.8))
        ws = [-5.0]
        for _ in range(n):
            ws.append(ws[-1] - eta * dL(ws[-1]))
        for wa, wb in zip(ws, ws[1:]):
            ya, yb = Y(L(wa)), Y(L(wb))
            yb_c = max(yb, Y(y1) - 6)
            body.append(path([(X(wa), ya), (X(wb), yb_c)], f'{p}-r', RED, 1.8))
        for w in ws:
            if L(w) <= y1:
                body.append(f'<circle cx="{f(X(w))}" cy="{f(Y(L(w)))}" r="3.8" fill="#000"/>')
        body.append(text(X(1.5), 26, f'{name}: η = {eta:g}', 17, w=700, c=[GREY, INK, RED][k]))
        body.append(text(X(1.5), 336, cap, 14, c=DARK))
        b.append(frag(k, body) if k else '\n'.join(body))
    return svg(p, 1100, 350, 'Gradient descent with learning rates that are too low, about right and too high', b,
               markers(p, {'r': RED}))


