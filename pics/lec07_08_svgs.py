# ---------- helpers ----------
def imul(a, b):
    r = (a * b) & 0xFFFFFFFF
    return r - (1 << 32) if r >= 1 << 31 else r


def rnd(a, b, c):
    """Same hash as the transformer animation, for the same look of tinted cells."""
    h = imul(a + 1, 374761393) ^ imul(b + 7, 668265263) ^ imul(c + 13, 1274126177)
    h = imul(h ^ ((h & 0xFFFFFFFF) >> 13), 1274126177)
    h ^= (h & 0xFFFFFFFF) >> 16
    return ((h & 0xFFFFFFFF) % 10007) / 10007


def mix(a, b, t):
    A = [int(a[i:i + 2], 16) for i in (1, 3, 5)]
    B = [int(b[i:i + 2], 16) for i in (1, 3, 5)]
    return '#' + ''.join(f'{round(x + (y - x) * t):02x}' for x, y in zip(A, B))


def f(v):
    return f'{v:.1f}'.rstrip('0').rstrip('.') if isinstance(v, float) else str(v)


def text(x, y, s, fs=14, a='middle', w=500, c=INK, mono=False, i=False, extra=''):
    """`s` may contain _x or _{xy} subscripts, ^x superscripts, rendered as tspans."""
    fam = f' font-family="{MONO}"' if mono else ''
    st = ' font-style="italic"' if i else ''
    import re
    s = re.sub(r'(?<![\w.])-(?=\d)', '\u2212', s)
    out, k, cur = [], 0, 0
    pos = 0
    for m in re.finditer(r'([_^])(\{[^}]*\}|.)', s):
        if m.start() > pos:
            out.append(f'<tspan dy="{f(-cur)}">{s[pos:m.start()]}</tspan>' if cur else s[pos:m.start()])
            cur = 0
        off = fs * 0.3 if m.group(1) == '_' else -fs * 0.4
        out.append(f'<tspan dy="{f(off - cur)}" font-size="{f(fs * 0.72)}">{m.group(2).strip("{}")}</tspan>')
        cur = off
        pos = m.end()
    if pos < len(s):
        out.append(f'<tspan dy="{f(-cur)}">{s[pos:]}</tspan>' if cur else s[pos:])
    return (f'<text x="{f(x)}" y="{f(y)}" text-anchor="{a}" '
            f'font-size="{f(fs)}" font-weight="{w}" fill="{c}"{fam}{st}{extra}>{"".join(out)}</text>')


def rect(x, y, w, h, fill, stroke='#222', sw=2.4, rx=7, extra=''):
    return (f'<rect x="{f(x)}" y="{f(y)}" width="{f(w)}" height="{f(h)}" rx="{f(rx)}" fill="{fill}" '
            f'stroke="{stroke}" stroke-width="{f(sw)}"{extra}/>')


def path(pts, mk, c='#222', w=2.2, dash=None, head=True):
    d = 'M' + ' L'.join(f'{f(x)} {f(y)}' for x, y in pts)
    da = f' stroke-dasharray="{dash}"' if dash else ''
    me = f' marker-end="url(#{mk})"' if head else ''
    return f'<path d="{d}" fill="none" stroke="{c}" stroke-width="{f(w)}" stroke-linejoin="round"{da}{me}/>'


def markers(p, cols):
    """One arrowhead marker per colour, ids prefixed so they are unique across the deck."""
    out = []
    for name, c in cols.items():
        out.append(f'<marker id="{p}-{name}" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="5" '
                   f'markerHeight="5" orient="auto"><path d="M0 0 L10 5 L0 10 z" fill="{c}"/></marker>')
    return out


def grid(x, y, rows, cols, cw, ch, color, seed, vals=None, stroke='#555'):
    """Tinted cells as in the animation; `vals` (0..1) overrides the random intensity."""
    out = ['<g>']
    for r in range(rows):
        for c in range(cols):
            t = vals[r][c] if vals else rnd(seed * 31 + r, c, seed)
            out.append(f'<rect x="{f(x + c * cw)}" y="{f(y + r * ch)}" width="{f(cw)}" height="{f(ch)}" '
                       f'fill="{mix("#ffffff", color, 0.25 + 0.75 * t)}" stroke="#fff" stroke-width="0.6"/>')
    out.append(f'<rect x="{f(x)}" y="{f(y)}" width="{f(cols * cw)}" height="{f(rows * ch)}" fill="none" '
               f'stroke="{stroke}" stroke-width="1"/>')
    out.append('</g>')
    return '\n'.join(out)


def svg(p, w, h, label, body, defs=()):
    return (f'<svg viewBox="0 0 {w} {h}" width="100%" xmlns="http://www.w3.org/2000/svg" font-family="{FONT}" '
            f'role="img" aria-label="{label}">\n<defs>{"".join(defs)}</defs>\n' + '\n'.join(body) + '\n</svg>')


def frag(i, body):
    return f'<g class="fragment" data-fragment-index="{i}">\n' + '\n'.join(body) + '\n</g>'


def bracket(x1, x2, y, label, c):
    return [f'<path d="M{x1} {y + 10} V{y} H{x2} V{y + 10}" fill="none" stroke="{c}" stroke-width="1.6"/>',
            text((x1 + x2) / 2, y - 10, label, 14, w=600, c=c)]


def oplus(cx, cy, r=13):
    return (f'<circle cx="{cx}" cy="{cy}" r="{r}" fill="#fff" stroke="#222" stroke-width="2"/>'
            f'<path d="M{cx - r} {cy} H{cx + r} M{cx} {cy - r} V{cy + r}" stroke="#222" stroke-width="2"/>')


