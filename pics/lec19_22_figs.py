"""Pack the lec19-22 GPU results into the images and data used by lec19.qmd ... lec22.qmd. CPU only, seconds.

The GPU jobs live in pics/lec19_22_gpu/ (see its README). Unzip what they send back so that the results are at
pics/lec19_22_raw/results/ (git-ignored), then, from the slides folder:

    python pics/lec19_22_figs.py

For each lecture NN this writes pics/lecNN/demo/*.jpg (the images the live demos switch between),
pics/lecNN/demos-data.js (window.LNNDATA: numbers and image paths) and a few static images for the slides.
The demos themselves are in pics/lec19_22_demos.js. A rerun of any GPU job can simply replace its files in
raw/results/: every image is looked up by name, and anything missing is left out of the demo.
"""
import json
import shutil
from pathlib import Path

import numpy as np
from PIL import Image

HERE = Path(__file__).resolve().parent
RAW = HERE / 'lec19_22_raw' / 'results'
INPUTS = HERE / 'lec19_22_gpu' / 'inputs'
SIZE = 320                                       # demo images are shown at about 280-300 px


def save(src, dst, size=SIZE, q=85):
    dst.parent.mkdir(parents=True, exist_ok=True)
    im = Image.open(src).convert('RGB')
    if size:
        im = im.resize((size, size), Image.LANCZOS)
    im.save(dst, quality=q)
    return dst


def write_data(n, data):
    js = (f'// Generated by pics/lec19_22_figs.py from pics/lec19_22_raw/results; do not edit.\n'
          f'window.L{n}DATA = ' + json.dumps(data, separators=(',', ':')) + ';\n')
    (HERE / f'lec{n}' / 'demos-data.js').write_text(js)
    print(f'lec{n}: demos-data.js', round(len(js) / 1e3, 1), 'kB')


def fresh(folder):
    if folder.exists():
        shutil.rmtree(folder)
    folder.mkdir(parents=True)
    return folder


# ---------------------------------------------------------------- lec19: DreamBooth
def lec19():
    R, OUT = RAW / 'lec19', HERE / 'lec19'
    demo = fresh(OUT / 'demo')
    sim = json.load(open(R / 'similarity.json'))
    steps = [0, 100, 200, 400, 800, 1200, 1600]
    keys = ['subject', 'beach', 'hat', 'paint', 'bucket', 'dog', 'park', 'cat']
    img, dino = {}, {}
    for run in ['prior', 'noprior']:
        for s in steps:
            folder = R / 'samples' / ('base' if s == 0 else f'{run}/{s:04d}')
            rel = 'base' if s == 0 else f'{run}/{s:04d}'
            for k in keys:
                for seed in [1, 2]:
                    f = folder / f'{k}-{seed}.jpg'
                    if not f.exists():
                        continue
                    name = f'{rel.replace("/", "-")}-{k}-{seed}.jpg'
                    if not (demo / name).exists():
                        save(f, demo / name)
                    img[f'{run}-{s}-{k}-{seed}'] = f'pics/lec19/demo/{name}'
                    dino[f'{run}-{s}-{k}-{seed}'] = sim['dino_per_image'].get(f'{rel}/{k}-{seed}.jpg')

    # Curves: mean DINO similarity to the five subject photos, per run and step
    subj_keys = ['subject', 'beach', 'hat', 'paint', 'bucket']
    curves = {}
    for run in ['prior', 'noprior']:
        subj, dog, cat = [], [], []
        for s in steps:
            rel = 'base' if s == 0 else f'{run}/{s:04d}'
            per = sim['dino_per_image']
            subj.append(round(float(np.mean([per[f'{rel}/{k}-{x}.jpg'] for k in subj_keys for x in [1, 2]])), 4))
            dog.append(sim['dino_drift'][rel]['to_subject'])
            cat.append(round(float(np.mean([per[f'{rel}/cat-{x}.jpg'] for x in [1, 2]])), 4))
        curves[run] = {'subject': subj, 'dog': dog, 'cat': cat}
    prompts = {'subject': 'a photo of sks dog', 'beach': 'a photo of sks dog running on a beach',
               'hat': 'a photo of sks dog wearing a red hat', 'paint': 'a watercolour painting of sks dog',
               'bucket': 'a photo of sks dog in a bucket', 'dog': 'a photo of a dog',
               'park': 'a dog playing in a park', 'cat': 'a photo of a cat'}
    write_data(19, {'steps': steps, 'keys': keys, 'prompts': prompts, 'img': img, 'dino': dino, 'curves': curves,
                    'ref': {'subject_self': sim['dino_subject_self'], 'class_to_subject': sim['dino_class_to_subject']}})

    # Static images
    save(R / 'class' / '000.jpg', OUT / 'class-0.jpg', size=256)
    for k in ['sks-1', 'sks-2', 'corgi-1']:
        save(R / 'samples' / 'base' / f'{k}.jpg', OUT / f'base-{k}.jpg', size=256)
    for run in ['prior', 'noprior']:
        for k in ['subject-1', 'dog-1', 'cat-1']:
            save(R / 'samples' / run / '0400' / f'{k}.jpg', OUT / f'{run}-400-{k}.jpg', size=256)
    for k in ['subject-1', 'dog-1', 'cat-1']:
        save(R / 'samples' / 'base' / f'{k}.jpg', OUT / f'base-{k}.jpg', size=256)

    # Memory and time, for the slide on our run
    def mem(run):
        v = [int(line.split(',')[1].split()[0]) for line in open(R / f'memory-{run}.csv') if 'MiB' in line]
        busy = [x for x in v if x > 1000]
        vals, counts = np.unique(busy, return_counts=True)
        return {'peak_GB': round(max(v) * 2**20 / 1e9, 2), 'steady_GB': round(int(vals[counts.argmax()]) * 2**20 / 1e9, 2)}
    log = json.load(open(RAW / 'lec19-log.json'))
    print('lec19 memory', {r: mem(r) for r in ['prior', 'noprior']},
          'time per step', {r: log[f'train_{r}']['per_item'] for r in ['prior', 'noprior']},
          'class images', log['class_images'])


# ---------------------------------------------------------------- lec20: image-to-image and inpainting
def alphabar():
    b = np.linspace(0.00085 ** 0.5, 0.012 ** 0.5, 1000) ** 2         # Stable Diffusion's scaled-linear schedule
    return np.cumprod(1 - b)


def lec20():
    R, OUT = RAW / 'lec20', HERE / 'lec20'
    demo = fresh(OUT / 'demo')
    info = json.load(open(R / 'img2img.json'))
    ab = alphabar()
    assert abs(ab[958] - info['alphabar_first_t']) < 1e-4, 'schedule does not match the run'
    img = {}
    for src in info['sources']:
        for s in info['strengths']:
            for name in [f'start-s{s}'] + [f's{s}-{x}' for x in [1, 2]]:
                save(R / 'img2img' / src / f'{name}.jpg', demo / f'{src}-{name}.jpg')
                img[f'{src}-{name}'] = f'pics/lec20/demo/{src}-{name}.jpg'
        for x in [1, 2]:
            save(R / 'img2img' / src / f't2i-{x}.jpg', demo / f'{src}-t2i-{x}.jpg')
            img[f'{src}-t2i-{x}'] = f'pics/lec20/demo/{src}-t2i-{x}.jpg'
        save(INPUTS / f'{src}.png', demo / f'{src}-input.jpg')
        img[f'{src}-input'] = f'pics/lec20/demo/{src}-input.jpg'
    start = {str(s): dict(v, alphabar=round(float(ab[v['t']]), 4)) for s, v in info['first_timestep'].items()}
    for f in sorted((R / 'inpaint').glob('*.jpg')):
        save(f, demo / f'inpaint-{f.name}')
        img[f'inpaint-{f.stem}'] = f'pics/lec20/demo/inpaint-{f.name}'
    for mk in ['tight', 'loose']:
        m = np.asarray(Image.open(INPUTS / f'coffee-mask-{mk}.png').convert('L').resize((SIZE, SIZE))) > 127
        photo = np.asarray(Image.open(INPUTS / 'coffee.png').convert('RGB').resize((SIZE, SIZE)), float)
        shade = photo.copy()
        shade[m] = 0.45 * photo[m] + 0.55 * np.array([255, 255, 255])
        Image.fromarray(shade.astype(np.uint8)).save(demo / f'coffee-{mk}.jpg', quality=85)
        img[f'coffee-{mk}'] = f'pics/lec20/demo/coffee-{mk}.jpg'
    write_data(20, {'sources': info['sources'], 'strengths': info['strengths'], 'steps': info['steps'],
                    'start': start, 'img': img, 'inpaint_prompt': json.load(open(R / 'inpaint.json'))['prompt']})
    for k in ['s0.8-1', 's1.0-1', 't2i-1']:
        save(R / 'img2img' / 'sketch' / f'{k}.jpg', OUT / f'sketch-{k}.jpg', size=256)
    for k in ['s0.6-1', 's1.0-1']:
        save(R / 'img2img' / 'cat' / f'{k}.jpg', OUT / f'cat-{k}.jpg', size=256)
    for method in ['blend', 'model']:
        for f in sorted((R / 'inpaint' / f'traj-{method}').glob('*.jpg')):
            save(f, OUT / f'traj-{method}-{f.stem}.jpg', size=160)
    print('lec20 start', start)


# ---------------------------------------------------------------- lec21: semantic image editing
def heat(map_file, image_file, dst):
    """Where an edit acted: mean |edit guidance| over the steps after warm-up, over a greyed copy of the image."""
    m = np.load(map_file).astype(float)
    a = m[np.abs(m).reshape(len(m), -1).max(1) > 0].mean(0)
    a = np.clip(a / np.percentile(a, 99.5), 0, 1)
    h = np.asarray(Image.fromarray((a * 255).astype(np.uint8)).resize((SIZE, SIZE), Image.BILINEAR), float) / 255
    g = np.asarray(Image.open(image_file).convert('L').resize((SIZE, SIZE)), float)[..., None] * np.ones(3)
    col = np.array([217, 72, 15], float)                               # the decks' orange
    out = (0.55 * g + 0.25 * 255) * (1 - h[..., None]) + col * h[..., None]
    Image.fromarray(np.clip(out, 0, 255).astype(np.uint8)).save(dst, quality=85)


def lec21():
    R, OUT = RAW / 'lec21', HERE / 'lec21'
    demo = fresh(OUT / 'demo')
    info = json.load(open(R / 'info.json'))
    img = {}
    for f in sorted((R / 'weight').glob('*.jpg')):
        save(f, demo / f'weight-{f.name}')
        img[f'weight-{f.stem}'] = f'pics/lec21/demo/weight-{f.name}'
    for f in sorted((R / 'sega').glob('*.jpg')):
        save(f, demo / f'sega-{f.name}')
        img[f'sega-{f.stem}'] = f'pics/lec21/demo/sega-{f.name}'
        mf = R / 'sega' / f'maps-{f.stem}.npy'
        if mf.exists():
            heat(mf, f, demo / f'sega-map-{f.name}')
            img[f'sega-map-{f.stem}'] = f'pics/lec21/demo/sega-map-{f.name}'
    for task in info['pix2pix']['tasks']:
        save(INPUTS / f'{task}.png', demo / f'p2p-{task}-input.jpg')
        img[f'p2p-{task}-input'] = f'pics/lec21/demo/p2p-{task}-input.jpg'
        for f in sorted((R / 'pix2pix' / task).glob('*.jpg')):
            save(f, demo / f'p2p-{task}-{f.name}')
            img[f'p2p-{task}-{f.stem}'] = f'pics/lec21/demo/p2p-{task}-{f.name}'
    w = info['weight']
    write_data(21, {'weight': {'weights': w['weights'], 'prompts': w['prompts']},
                    'sega': info['sega'], 'pix2pix': info['pix2pix'], 'img': img})
    save(INPUTS / 'cat.png', OUT / 'cat.jpg', size=256)
    for f in sorted((R / 'invert').glob('*.jpg')):
        save(f, OUT / f'invert-{f.name}', size=256)
    print('lec21 inversion', info['inversion'])


