# ---------- helpers ----------
def text(x, y, s, fs=14, **k):
    return _text(x, y, s, fs * SC, **k)


def raw(x, y, s, fs=14, a='middle', w=500, c='#000', mono=False, i=False):
    """Like text(), but with no _ or ^ handling, for code identifiers."""
    fs *= SC
    fam = f' font-family="{MONO}"' if mono else ''
    st = ' font-style="italic"' if i else ''
    return (f'<text x="{f(x)}" y="{f(y)}" text-anchor="{a}" font-size="{f(fs)}" font-weight="{w}" '
            f'fill="{c}"{fam}{st}>{s}</text>')


def box(x, y, w, h, fill, label, fs=17, sub=None, rx=7):
    out = [rect(x, y, w, h, fill, rx=rx)]
    cy = y + h / 2
    out.append(text(x + w / 2, cy + (-3 if sub else 6), label, fs, w=600))
    if sub:
        out.append(text(x + w / 2, cy + 16, sub, 13, c=DARK))
    return out


def vstrip(x, y, n, cw, ch, active=(), color=ACC, dense=None):
    """A vector as a column of cells; `dense` fills every cell, otherwise only `active` ones."""
    out = []
    for r in range(n):
        if dense:
            fill = mix('#ffffff', dense, 0.25 + 0.75 * rnd(5, r, 9))
        else:
            fill = color if r in active else '#fff'
        out.append(f'<rect x="{f(x)}" y="{f(y + r * ch)}" width="{f(cw)}" height="{f(ch)}" fill="{fill}"/>')
    out.append(f'<rect x="{f(x)}" y="{f(y)}" width="{f(cw)}" height="{f(n * ch)}" fill="none" stroke="#555" '
               f'stroke-width="1"/>')
    return out


def ray(p, cx, cy, ang, r, c, mk, w=2.6):
    x, y = cx + r * math.cos(ang), cy - r * math.sin(ang)
    return path([(cx, cy), (x, y)], f'{p}-{mk}', c, w), (x, y)


def jpg(name):
    return 'data:image/jpeg;base64,' + base64.b64encode((HERE / 'lec14' / f'{name}.jpg').read_bytes()).decode()


def photo(x, y, s, name, stroke='#555'):
    return (f'<image x="{f(x)}" y="{f(y)}" width="{f(s)}" height="{f(s)}" href="{jpg(name)}"/>'
            f'<rect x="{f(x)}" y="{f(y)}" width="{f(s)}" height="{f(s)}" fill="none" stroke="{stroke}" stroke-width="1"/>')


def patch(x, y, s, r, c, n=16):
    """Patch (r, c) of the 224px cat, in an n x n grid, drawn s pixels across. No nested <svg>:
    the marker regex stops at the first </svg>."""
    cid = f'l14c{r}-{c}'
    full = s * n
    return (f'<clipPath id="{cid}"><rect x="{f(x)}" y="{f(y)}" width="{f(s)}" height="{f(s)}"/></clipPath>'
            f'<image x="{f(x - c * s)}" y="{f(y - r * s)}" width="{f(full)}" height="{f(full)}" '
            f'href="{jpg("cat224")}" clip-path="url(#{cid})"/>'
            f'<rect x="{f(x)}" y="{f(y)}" width="{f(s)}" height="{f(s)}" fill="none" stroke="#555" stroke-width="1"/>')


