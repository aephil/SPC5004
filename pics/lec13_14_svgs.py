def lec13_penalty():
    p = 'l13p'
    b = []
    # left: the penalties themselves
    x0, y0, w, h = 90, 40, 400, 220
    cx = x0 + w / 2
    Xf = lambda v: cx + v * w / 4
    Yf = lambda v: y0 + h - v * h / 2.2
    b.append(f'<path d="M{x0} {y0 + h} H{x0 + w} M{f(cx)} {y0} V{y0 + h}" fill="none" stroke="#222" stroke-width="1.8"/>')
    b.append(text(cx, y0 + h + 30, 'z', 16, w=600, i=True))
    b.append(text(cx, y0 - 12, 'penalty', 15, w=600))
    for v in (-2, -1, 1, 2):
        b.append(text(Xf(v), y0 + h + 20, str(v), 13, c=DARK))
    vs = [(-2 + i * 0.02) for i in range(201)]
    l2 = [(Xf(v), Yf(v * v)) for v in vs if v * v <= 2.2]
    b.append(path(l2, '', BLUE, 3, head=False))
    b.append(path([(Xf(-2), Yf(2)), (Xf(0), Yf(0)), (Xf(2), Yf(2))], '', ACC, 3, head=False))
    b.append(text(Xf(2) + 8, Yf(2) + 8, '|z|', 17, a='start', w=700, c=ACC))
    b.append(text(Xf(1.48) + 8, Yf(2.19) + 12, 'z^2', 17, a='start', w=700, c=BLUE))
    # right: repeated penalty-only steps
    x0, y0, w, h = 650, 40, 400, 220
    Xs = lambda n: x0 + n * w / 20
    Ys = lambda v: y0 + h - v * h / 1.05
    b += chart_axes(x0, y0, w, h, 'steps', 'z')
    for n in (5, 10, 15, 20):
        b.append(text(Xs(n), y0 + h + 18, str(n), 13, c=DARK))
    b.append(text(x0 - 8, Ys(1) + 5, '1', 13, a='end', c=DARK))
    l1 = [max(0.0, 1 - 0.1 * n) for n in range(21)]
    l2v = [0.9 ** n for n in range(21)]
    b.append(path([(Xs(n), Ys(v)) for n, v in enumerate(l2v)], '', BLUE, 3, head=False))
    b.append(path([(Xs(n), Ys(v)) for n, v in enumerate(l1)], '', ACC, 3, head=False))
    b.append(text(Xs(0.7), Ys(0.1), 'L1: hits 0', 16, a='start', w=700, c=ACC))
    b.append(text(Xs(6.5), Ys(0.72), 'L2: never quite gets there', 16, a='start', w=700, c=BLUE))
    return svg(p, 1100, 312, 'Left, the L1 and L2 penalties plotted against z. Right, z shrinking under each penalty alone', b)


def bars(x0, ybase, vals, title, col, bw=44, gap=10, scale=74):
    out = [text(x0 + 3 * (bw + gap) - gap / 2, 26, title, 17, w=700)]
    out.append(f'<path d="M{x0 - 6} {ybase} H{x0 + 6 * (bw + gap)}" stroke="#222" stroke-width="1.8"/>')
    for k, v in enumerate(vals):
        x = x0 + k * (bw + gap)
        if v > 0:
            out.append(f'<rect x="{f(x)}" y="{f(ybase - v * scale)}" width="{bw}" height="{f(v * scale)}" fill="{col}"/>')
            out.append(text(x + bw / 2, ybase - v * scale - 7, f'{v}', 14, w=600))
        else:
            out.append(text(x + bw / 2, ybase - 7, '0', 14, c=GREY))
    return out


