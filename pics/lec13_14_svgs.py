def hbars(x0, y0, rows, title, full, lw):
    out = [text(x0 + (lw + full) / 2, 20, title, 17, w=700)]
    for k, (lab, v) in enumerate(rows):
        y = y0 + k * 36
        out.append(raw(x0 + lw - 10, y + 19, lab, 15, a='end'))
        w = max(1.5, full * v / 100)
        out.append(f'<rect x="{x0 + lw}" y="{y}" width="{f(w)}" height="24" fill="{ACC if k == 0 else mix("#ffffff", ACC, 0.5)}"/>')
        out.append(text(x0 + lw + w + 8, y + 20, f'{v:.1f}%', 15, a='start', w=600))
    return out


